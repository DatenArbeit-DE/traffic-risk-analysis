"""Thin PostgreSQL helpers built on psycopg 3 (no ORM).

Keeping the data access layer explicit (SQL in, dicts out) makes the pipeline
auditable: every statement that touches personal-data-adjacent tables can be
read in one place, and nothing is generated by an abstraction layer.
"""

from __future__ import annotations

import logging
from contextlib import contextmanager
from typing import Any, Iterable, Iterator, Sequence

import psycopg
from psycopg.rows import dict_row

from .config import Settings

log = logging.getLogger(__name__)


@contextmanager
def transaction(settings: Settings) -> Iterator[psycopg.Connection]:
    """Open a connection with one transaction; commit on success, rollback on error."""
    conn = psycopg.connect(settings.dsn, row_factory=dict_row)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def fetch_all(conn: psycopg.Connection, sql: str, params: dict[str, Any] | None = None) -> list[dict]:
    with conn.cursor() as cur:
        cur.execute(sql, params)
        return cur.fetchall()


def fetch_one(conn: psycopg.Connection, sql: str, params: dict[str, Any] | None = None) -> dict | None:
    with conn.cursor() as cur:
        cur.execute(sql, params)
        return cur.fetchone()


def execute(conn: psycopg.Connection, sql: str, params: dict[str, Any] | None = None) -> int:
    """Execute a statement and return the number of affected rows."""
    with conn.cursor() as cur:
        cur.execute(sql, params)
        return cur.rowcount


def copy_rows(
    conn: psycopg.Connection,
    table: str,
    columns: Sequence[str],
    rows: Iterable[Sequence[Any]],
) -> int:
    """Bulk load rows with COPY (text mode), which handles large batches cheaply."""
    column_list = ", ".join(columns)
    written = 0
    with conn.cursor() as cur, cur.copy(f"COPY {table} ({column_list}) FROM STDIN") as copy:
        for row in rows:
            copy.write_row(row)
            written += 1
    return written


def purge_expired(conn: psycopg.Connection, settings: Settings) -> dict[str, int]:
    """Apply the retention policy defined in sql/03_retention.sql.

    The file is the single source of truth (auditors can run it by hand), so it
    is parsed here instead of duplicating the statements in Python.
    """
    retention_file = settings.sql_dir / "03_retention.sql"
    statements = _split_sql(retention_file.read_text(encoding="utf-8"))

    purged: dict[str, int] = {}
    with conn.cursor() as cur:
        for index, statement in enumerate(statements, start=1):
            cur.execute(statement)
            purged[f"statement_{index}"] = cur.rowcount
    log.info("retention purge finished: %s", purged)
    return purged


def _split_sql(script: str) -> list[str]:
    """Split a script into statements, respecting quotes and comments.

    A naive ``script.split(";")`` breaks on semicolons inside string literals
    (``COMMENT ON TABLE ... IS 'landing zone; purged'``), so this scanner tracks
    single/double quotes and skips ``--`` and ``/* */`` comments.
    """
    statements: list[str] = []
    buffer: list[str] = []
    index = 0
    length = len(script)
    in_single = False
    in_double = False

    while index < length:
        char = script[index]
        following = script[index + 1] if index + 1 < length else ""

        if in_single:
            buffer.append(char)
            if char == "'":
                if following == "'":  # doubled quote - still inside the literal
                    buffer.append(following)
                    index += 2
                    continue
                in_single = False
            index += 1
            continue

        if in_double:
            buffer.append(char)
            if char == '"':
                in_double = False
            index += 1
            continue

        if char == "-" and following == "-":
            newline = script.find("\n", index)
            index = length if newline == -1 else newline
            continue

        if char == "/" and following == "*":
            closing = script.find("*/", index + 2)
            index = length if closing == -1 else closing + 2
            continue

        if char in ("'", '"'):
            in_single = char == "'"
            in_double = char == '"'
            buffer.append(char)
            index += 1
            continue

        if char == ";":
            statement = "".join(buffer).strip()
            if statement:
                statements.append(statement)
            buffer = []
            index += 1
            continue

        buffer.append(char)
        index += 1

    tail = "".join(buffer).strip()
    if tail:
        statements.append(tail)
    return statements


def table_columns(conn: psycopg.Connection, schema: str, table: str) -> list[dict]:
    """Column metadata, used by the PII guard tests and the `verify` CLI."""
    return fetch_all(
        conn,
        """
        SELECT column_name, data_type
        FROM information_schema.columns
        WHERE table_schema = %(schema)s AND table_name = %(table)s
        ORDER BY ordinal_position
        """,
        {"schema": schema, "table": table},
    )


def ping(settings: Settings) -> bool:
    """Cheap connectivity check used by the CLI and the DAG's first task."""
    with transaction(settings) as conn:
        return fetch_one(conn, "SELECT 1 AS ok") is not None
